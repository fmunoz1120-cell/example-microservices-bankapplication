CREATE TABLE persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    complete_name VARCHAR(200) NOT NULL,
    dni_type_id BIGINT NOT NULL,
    dni VARCHAR(20) NOT NULL,
    gender VARCHAR(3) NOT NULL,
    age INTEGER NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_persons PRIMARY KEY (id),
    CONSTRAINT uq_persons_dni UNIQUE (dni),
    CONSTRAINT chk_persons_age_valid CHECK (age BETWEEN 0 AND 150),
    CONSTRAINT chk_persons_dni_type_id_positive CHECK (dni_type_id > 0)
);
CREATE INDEX idx_persons_dni_type_id ON persons(dni_type_id);

CREATE TABLE clients (
    id BIGINT NOT NULL,
    password VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_clients PRIMARY KEY (id),
    CONSTRAINT fk_clients_persons FOREIGN KEY (id) REFERENCES persons(id),
    CONSTRAINT chk_clients_active_deleted_at_consistent CHECK (
        (is_active = TRUE AND deleted_at IS NULL)
        OR (is_active = FALSE AND deleted_at IS NOT NULL)
    )
);

CREATE TABLE outbox_events (
    id UUID NOT NULL,
    client_id BIGINT NOT NULL,
    payload TEXT NOT NULL,
    is_published BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_outbox_events PRIMARY KEY (id),
    CONSTRAINT fk_outbox_events_clients FOREIGN KEY (client_id) REFERENCES clients(id)
);

-- The primary key already indexes the shared foreign key clients.id.
CREATE INDEX idx_outbox_events_client_id ON outbox_events(client_id);
CREATE INDEX idx_outbox_events_client_id_id ON outbox_events(client_id, id)
WHERE is_published = FALSE;

CREATE FUNCTION fn_set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    RAISE;
END;
$$;

CREATE TRIGGER trg_persons_updated_at_before_update
BEFORE UPDATE ON persons
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TRIGGER trg_clients_updated_at_before_update
BEFORE UPDATE ON clients
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TRIGGER trg_outbox_events_updated_at_before_update
BEFORE UPDATE ON outbox_events
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
