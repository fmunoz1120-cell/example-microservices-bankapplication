CREATE TABLE catalog_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    catalog_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_catalog_types PRIMARY KEY (id)
);

CREATE TABLE catalog_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    catalog_type_id BIGINT NOT NULL,
    value_code VARCHAR(50) NOT NULL,
    value_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_catalog_values PRIMARY KEY (id),
    CONSTRAINT fk_catalog_values_catalog_types FOREIGN KEY (catalog_type_id) REFERENCES catalog_types(id),
    CONSTRAINT uq_catalog_values_catalog_type_id_value_code UNIQUE (catalog_type_id, value_code)
);
CREATE INDEX idx_catalog_values_catalog_type_id ON catalog_values(catalog_type_id);

CREATE TABLE work_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    area_name VARCHAR(100) NOT NULL,
    area_address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    area_type_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_work_areas PRIMARY KEY (id),
    CONSTRAINT fk_work_areas_catalog_values FOREIGN KEY (area_type_id) REFERENCES catalog_values(id)
);
CREATE INDEX idx_work_areas_area_type_id ON work_areas(area_type_id);

CREATE FUNCTION fn_set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    RAISE;
END;
$$;

CREATE TRIGGER trg_catalog_types_updated_at_before_update
BEFORE UPDATE ON catalog_types
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
CREATE TRIGGER trg_catalog_values_updated_at_before_update
BEFORE UPDATE ON catalog_values
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
CREATE TRIGGER trg_work_areas_updated_at_before_update
BEFORE UPDATE ON work_areas
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

