CREATE TABLE client_projections (
    id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL,
    event_version BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_client_projections PRIMARY KEY (id)
);

CREATE TABLE processed_events (
    id UUID NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_processed_events PRIMARY KEY (id)
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_number VARCHAR(20) NOT NULL,
    account_type_id BIGINT NOT NULL,
    account_created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    work_area_id BIGINT NOT NULL,
    client_projection_id BIGINT NOT NULL,
    initial_amount NUMERIC(19,2) NOT NULL,
    balance NUMERIC(19,2) NOT NULL,
    is_active BOOLEAN NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT uq_accounts_account_number UNIQUE (account_number),
    CONSTRAINT fk_accounts_client_projections FOREIGN KEY (client_projection_id)
        REFERENCES client_projections(id),
    CONSTRAINT chk_accounts_initial_amount_nonnegative CHECK (initial_amount >= 0),
    CONSTRAINT chk_accounts_balance_nonnegative CHECK (balance >= 0),
    CONSTRAINT chk_accounts_account_type_id_positive CHECK (account_type_id > 0),
    CONSTRAINT chk_accounts_work_area_id_positive CHECK (work_area_id > 0),
    CONSTRAINT chk_accounts_active_deleted_at_consistent CHECK (
        (is_active = TRUE AND deleted_at IS NULL)
        OR (is_active = FALSE AND deleted_at IS NOT NULL)
    )
);
CREATE INDEX idx_accounts_client_projection_id ON accounts(client_projection_id);
CREATE INDEX idx_accounts_account_type_id ON accounts(account_type_id);
CREATE INDEX idx_accounts_work_area_id ON accounts(work_area_id);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id BIGINT NOT NULL,
    transaction_date TIMESTAMP WITH TIME ZONE NOT NULL,
    transaction_type_id BIGINT NOT NULL,
    work_area_id BIGINT NOT NULL,
    amount NUMERIC(19,2) NOT NULL,
    balance NUMERIC(19,2) NOT NULL,
    reversed_transaction_id BIGINT NULL,
    replaced_transaction_id BIGINT NULL,
    is_reversed BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (id),
    CONSTRAINT fk_transactions_accounts FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT fk_transactions_transactions_reversed FOREIGN KEY (reversed_transaction_id)
        REFERENCES transactions(id),
    CONSTRAINT fk_transactions_transactions_replaced FOREIGN KEY (replaced_transaction_id)
        REFERENCES transactions(id),
    CONSTRAINT uq_transactions_reversed_transaction_id UNIQUE (reversed_transaction_id),
    CONSTRAINT chk_transactions_amount_nonzero CHECK (amount <> 0),
    CONSTRAINT chk_transactions_balance_nonnegative CHECK (balance >= 0),
    CONSTRAINT chk_transactions_transaction_type_id_positive CHECK (transaction_type_id > 0),
    CONSTRAINT chk_transactions_work_area_id_positive CHECK (work_area_id > 0),
    CONSTRAINT chk_transactions_amount_sign CHECK (
        (transaction_type_id = 301 AND amount > 0)
        OR (transaction_type_id = 302 AND amount < 0)
    )
);

COMMENT ON COLUMN transactions.reversed_transaction_id IS
    'Original transaction compensated by this reversal entry';
COMMENT ON COLUMN transactions.replaced_transaction_id IS
    'Original transaction replaced by this new entry';
-- The composite index covers account_id; the unique constraint covers reversed_transaction_id.
CREATE INDEX idx_transactions_account_id_transaction_date_id
    ON transactions(account_id, transaction_date, id);
CREATE INDEX idx_transactions_replaced_transaction_id
    ON transactions(replaced_transaction_id);
CREATE INDEX idx_transactions_transaction_type_id ON transactions(transaction_type_id);
CREATE INDEX idx_transactions_work_area_id ON transactions(work_area_id);

CREATE FUNCTION fn_set_updated_at() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
EXCEPTION WHEN OTHERS THEN
    RAISE;
END;
$$;

CREATE TRIGGER trg_client_projections_updated_at_before_update
BEFORE UPDATE ON client_projections
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TRIGGER trg_processed_events_updated_at_before_update
BEFORE UPDATE ON processed_events
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TRIGGER trg_accounts_updated_at_before_update
BEFORE UPDATE ON accounts
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TRIGGER trg_transactions_updated_at_before_update
BEFORE UPDATE ON transactions
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
